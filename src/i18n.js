// CA and EN are incomplete: fall back key by key to Spanish so a missing
// translation shows Spanish text instead of an empty label.
const RESOLVED = Object.fromEntries(
  Object.entries(TRANSLATIONS).map(([lang, dict]) => [lang, { ...TRANSLATIONS.es, ...dict }])
);

export function useT() {
  const appLang = useStore(s => s.config?.appLang || 'es');
  return RESOLVED[appLang] || RESOLVED.es;
}

// BCP 47 locale for dates and month/day names in the app language
export const DATE_LOCALES = { es: 'es-ES', ca: 'ca-ES', en: 'en-GB' };

export function useLocale() {
  const appLang = useStore(s => s.config?.appLang || 'es');
  return DATE_LOCALES[appLang] || DATE_LOCALES.es;
}

// Picks `key` for n === 1 and `key_plural` otherwise, then fills {n}
export function plural(t, key, n) {
  const text = n === 1 ? t[key] : (t[`${key}_plural`] ?? t[key]);
  return text.replace('{n}', n);
}

export default useT;
